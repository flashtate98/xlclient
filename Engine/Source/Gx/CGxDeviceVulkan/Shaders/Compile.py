"""Compiles the GLSL under this folder to SPIR-V and writes the .inc files of uint32_t arrays the
backend embeds: Spirv.inc (the draw programs, Vulkan/Pipelines/Programs.cpp) and PresentSpirv.inc
(the present pass, Vulkan/Present.cpp).

The .inc files are committed: a build needs no glslang. Run this after editing a shader:

    python Compile.py [path/to/glslang.exe]

glslang is taken from the argument, else from GLSLANG in the environment, else from PATH. The
shaders #include Push.glsl, which glslang resolves relative to the source (-l enables the include
extension).
"""

import os
import shutil
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUTS = [
    ("Spirv.inc", [
        ("Ff.vert", "kFfVert"),
        ("Ff.frag", "kFfFrag"),
        ("Ui.vert", "kUiVert"),
        ("Ui.frag", "kUiFrag"),
        ("Desaturate.frag", "kDesaturateFrag"),
        ("FfSem.vert", "kFfSemVert"),
        ("FfTranslated.frag", "kFfTranslatedFrag"),
    ]),
    ("PresentSpirv.inc", [
        ("Present.vert", "kPresentVert"),
        ("Present.frag", "kPresentFrag"),
    ]),
    # SXC: the volumetric fog (Vulkan/Fog.cpp); its full-screen pass reuses Present.vert.
    ("FogSpirv.inc", [
        ("Fog.comp", "kFogComp"),
        ("Fog.frag", "kFogFrag"),
        ("FogLights.comp", "kFogLightsComp"),  # our lights in the fog: the light volume
    ]),
    # SXC: the lights' cube shadow maps (Vulkan/Shadows.cpp), depth only; alpha-keyed parts discard.
    ("ShadowSpirv.inc", [
        ("LightShadow.vert", "kLightShadowVert"),
        ("LightShadowAlpha.frag", "kLightShadowAlphaFrag"),
    ]),
    # SXC: our terrain shader (Vulkan/Pipelines/Terrain.cpp): one vertex module; the pixel source once
    # per layer count and shadow group (the samplers a module declares must all be bound), the finer
    # options as specialization constants. Twice: the cover textures in 16 slots (any device), and in
    # one array indexed per pixel ("B": a Vulkan 1.2 device with non-uniform indexing; SPIR-V 1.5).
    ("TerrainSpirv.inc", [("Terrain.vert", "kTerrainVert")] + [
        ("Terrain.frag", f"kTerrainFrag{layers}{shadow}", [f"LAYERS={layers}", f"SHADOW={shadow}"])
        for layers in range(1, 5) for shadow in range(3)
    ] + [
        ("Terrain.frag", f"kTerrainFrag{layers}{shadow}B", [f"LAYERS={layers}", f"SHADOW={shadow}", "COVER_BINDLESS=1"], "vulkan1.2")
        for layers in range(1, 5) for shadow in range(3)
    ] + [
        # Chunks raised onto their covers (step 5c): the vertex as it is, the subdivision, the raised
        # points (both once per layer count: the alpha map's binding is the layer count).
        ("TerrainPatch.vert", "kTerrainPatchVert"),
    ] + [
        ("Terrain.tesc", f"kTerrainTesc{layers}", [f"LAYERS={layers}"])
        for layers in range(1, 5)
    ] + [
        ("Terrain.tese", f"kTerrainTese{layers}", [f"LAYERS={layers}"])
        for layers in range(1, 5)
    ] + [
        # The client's projected textures on the raised covers (step 5e).
        ("Decal.vert", "kDecalVert"),
        ("Decal.frag", "kDecalFrag"),
    ]),
]


def find_glslang():
    if len(sys.argv) > 1:
        return sys.argv[1]
    if os.environ.get("GLSLANG"):
        return os.environ["GLSLANG"]
    for name in ("glslang", "glslangValidator"):
        found = shutil.which(name)
        if found:
            return found
    sys.exit("glslang not found: pass its path, set GLSLANG, or put it on PATH")


def write_inc(glslang, out_name, shaders):
    # Each entry: (source, symbol), (source, symbol, [preprocessor defines]) or (source, symbol,
    # [defines], target env); the target env is vulkan1.0 unless named.
    names = ", ".join(sorted({entry[0] for entry in shaders}))
    lines = [
        f"// Generated by Shaders/Compile.py from {names}: SPIR-V 1.0 for Vulkan 1.0 (unless a module",
        "// says otherwise), as uint32_t words. Do not edit; edit the GLSL and run the script.",
        "",
    ]
    for entry in shaders:
        source, symbol = entry[0], entry[1]
        defines = ["-D" + d for d in (entry[2] if len(entry) > 2 else [])]
        env = entry[3] if len(entry) > 3 else "vulkan1.0"
        spv = os.path.join(HERE, symbol + ".spv")
        subprocess.check_call([glslang, "-V", "-l", "-Os", "--target-env", env, "-I" + HERE] + defines + [os.path.join(HERE, source), "-o", spv])
        if env != "vulkan1.0":
            lines.append(f"// {symbol}: {env}")
        with open(spv, "rb") as f:
            data = f.read()
        os.remove(spv)
        if len(data) % 4:
            sys.exit(f"{source}: SPIR-V size is not a multiple of 4")
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        lines.append(f"static const uint32_t {symbol}[] = {{")
        for i in range(0, len(words), 8):
            lines.append("    " + ", ".join("0x%08X" % w for w in words[i:i + 8]) + ",")
        lines.append("};")
        lines.append("")
    out = os.path.join(HERE, out_name)
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {out}")


def main():
    glslang = find_glslang()
    for out_name, shaders in OUTPUTS:
        write_inc(glslang, out_name, shaders)


if __name__ == "__main__":
    main()
